"""install-launchers.sh installs stable scripts that resolve the newest cache."""
import os
import shutil
import subprocess
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INSTALLER = os.path.join(ROOT, 'install-launchers.sh')
NAMES = ('task.py', 'quota.py', 'skill-updates.py', 'clean-sessions.py', 'task')


class InstallLaunchersTest(unittest.TestCase):
    def setUp(self):
        self.home = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.home, True)
        self.dest = os.path.join(self.home, '.claude', 'scripts')
        os.makedirs(self.dest)
        self.env = dict(os.environ, HOME=self.home)
        self.cache = os.path.join(self.home, '.claude', 'plugins', 'cache')
        for version in ('2.22.4', '2.23.0', '2.23.0-rc1', '2.23.0.bak'):
            self.add_version('market', version)
        os.symlink(os.path.join(self.cache, 'market', 'task-runner', '2.23.0'),
                   os.path.join(self.cache, 'market', 'task-runner', '9.9.9'))

    def add_version(self, market, version):
        folder = os.path.join(self.cache, market, 'task-runner', version, 'scripts')
        os.makedirs(folder, exist_ok=True)
        for name in set(NAMES) - {'task'}:
            path = os.path.join(folder, name)
            with open(path, 'w') as handle:
                handle.write('#!/bin/sh\nprintf "%s\\n" "' + version + '"\nprintf "args:"; printf " <%s>" "$@"; printf "\\nstdin:"; cat\n')
            os.chmod(path, 0o755)

    def install(self, env=None):
        return subprocess.run(['bash', INSTALLER, '--dest', self.dest], env=env or self.env,
                              capture_output=True, text=True)

    def run_launcher(self, name, args=(), stdin='input\n'):
        return subprocess.run([os.path.join(self.dest, name), *args], env=self.env,
                              input=stdin, capture_output=True, text=True)

    def test_newest_numeric_version_and_later_cache_are_selected(self):
        self.assertEqual(0, self.install().returncode)
        result = self.run_launcher('task.py', ('one', 'two'))
        self.assertEqual(0, result.returncode, result.stderr)
        self.assertIn('2.23.0\n', result.stdout)
        self.assertIn('args: <one> <two>', result.stdout)
        self.assertIn('stdin:input', result.stdout)
        self.add_version('market', '2.24.0')
        self.assertIn('2.24.0\n', self.run_launcher('task.py').stdout)

    def test_symlink_replaced_by_real_executable(self):
        old = os.path.join(self.home, 'old')
        open(old, 'w').close()
        os.symlink(old, os.path.join(self.dest, 'quota.py'))
        self.install()
        path = os.path.join(self.dest, 'quota.py')
        self.assertFalse(os.path.islink(path))
        self.assertTrue(os.access(path, os.X_OK))

    def test_foreign_real_file_is_untouched(self):
        path = os.path.join(self.dest, 'quota.py')
        with open(path, 'w') as handle:
            handle.write('#!/bin/sh\nkeep me\n')
        result = self.install()
        self.assertEqual(0, result.returncode)
        self.assertIn('skipping existing file', result.stderr)
        with open(path) as handle:
            self.assertEqual('#!/bin/sh\nkeep me\n', handle.read())

    def test_no_cache_exits_127_with_message(self):
        shutil.rmtree(self.cache)
        self.install()
        result = self.run_launcher('task')
        self.assertEqual(127, result.returncode)
        self.assertIn('no cached task-runner version found', result.stderr)

    def test_install_is_idempotent(self):
        self.install()
        path = os.path.join(self.dest, 'task.py')
        before = os.stat(path).st_mtime_ns
        with open(path, 'rb') as handle:
            content = handle.read()
        self.assertEqual(0, self.install().returncode)
        with open(path, 'rb') as handle:
            self.assertEqual(content, handle.read())
        self.assertEqual(before, os.stat(path).st_mtime_ns)

    def test_cat_write_failure_preserves_existing_launcher(self):
        path = os.path.join(self.dest, 'task.py')
        original = '#!/bin/bash\n# generated by install-launchers.sh\noriginal\n'
        with open(path, 'w') as handle:
            handle.write(original)
        os.chmod(path, 0o755)

        fake_bin = os.path.join(self.home, 'bin')
        os.makedirs(fake_bin)
        fake_cat = os.path.join(fake_bin, 'cat')
        with open(fake_cat, 'w') as handle:
            handle.write('#!/bin/sh\nprintf partial\nexit 1\n')
        os.chmod(fake_cat, 0o755)
        env = dict(self.env, PATH=fake_bin + os.pathsep + os.environ['PATH'])

        result = self.install(env)

        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        self.assertIn('cannot write launcher', result.stderr)
        with open(path) as handle:
            self.assertEqual(original, handle.read())
        self.assertEqual([], [name for name in os.listdir(self.dest)
                              if name.startswith('.task.py.')])

    def test_unwritable_dest_exits_zero_with_stderr_note(self):
        os.chmod(self.dest, 0o555)
        self.addCleanup(os.chmod, self.dest, 0o755)
        probe = os.path.join(self.dest, '.probe')
        try:
            with open(probe, 'w'):
                pass
        except PermissionError:
            pass
        else:
            os.unlink(probe)
            self.skipTest('chmod 0555 does not prevent writes for this user')

        result = self.install()
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        self.assertTrue(result.stderr.strip())

    def test_identical_launcher_with_non_executable_mode_is_replaced(self):
        self.assertEqual(0, self.install().returncode)
        path = os.path.join(self.dest, 'task.py')
        os.chmod(path, 0o644)

        result = self.install()

        self.assertEqual(0, result.returncode, result.stderr)
        self.assertTrue(os.access(path, os.X_OK))

    def test_symlink_to_identical_launcher_is_replaced(self):
        self.assertEqual(0, self.install().returncode)
        path = os.path.join(self.dest, 'task.py')
        target = os.path.join(self.home, 'identical')
        shutil.copyfile(path, target)
        os.chmod(target, 0o755)
        os.unlink(path)
        os.symlink(target, path)

        result = self.install()

        self.assertEqual(0, result.returncode, result.stderr)
        self.assertFalse(os.path.islink(path))
        self.assertTrue(os.access(path, os.X_OK))


if __name__ == '__main__':
    unittest.main()
