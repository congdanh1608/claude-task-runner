#!/bin/bash
# Install stable launchers that resolve the newest cached task-runner scripts.
set -u

DEST=${HOME}/.claude/scripts
if [ "${1-}" = --dest ]; then
  [ "$#" -eq 2 ] || { echo "usage: install-launchers.sh [--dest DIR]" >&2; exit 2; }
  DEST=$2
elif [ "$#" -ne 0 ]; then
  echo "usage: install-launchers.sh [--dest DIR]" >&2
  exit 2
fi

names="task.py quota.py skill-updates.py clean-sessions.py task"
mkdir -p "$DEST" 2>/dev/null || { echo "install-launchers: cannot create destination: $DEST" >&2; exit 0; }

for name in $names; do
  target=$name
  [ "$name" = task ] && target=task.py
  path="$DEST/$name"
  if [ -e "$path" ] && [ ! -L "$path" ]; then
    marker=$(sed -n '2p' "$path" 2>/dev/null || true)
    if [ "$marker" != "# generated by install-launchers.sh" ]; then
      echo "install-launchers: skipping existing file: $path" >&2
      continue
    fi
  fi
  tmp=$(mktemp "$DEST/.${name}.XXXXXX" 2>/dev/null) || { echo "install-launchers: cannot create temporary file for $path" >&2; exit 0; }
  if ! cat > "$tmp" <<EOF_LAUNCHER
#!/bin/bash
# generated by install-launchers.sh
versions=()
for dir in "\$HOME"/.claude/plugins/cache/*/task-runner/*/; do
  [ -d "\$dir" ] && [ ! -L "\${dir%/}" ] || continue
  version=\${dir%/}
  version=\${version##*/}
  [[ \$version =~ ^[0-9]+(\\.[0-9]+)*\$ ]] || continue
  versions+=("\$version")
done
if [ \${#versions[@]} -eq 0 ]; then
  echo "${name}: no cached task-runner version found" >&2
  exit 127
fi
version=\$(printf '%s\n' "\${versions[@]}" | sort -V | tail -n 1)
script=
for dir in "\$HOME"/.claude/plugins/cache/*/task-runner/*/; do
  [ -d "\$dir" ] && [ ! -L "\${dir%/}" ] || continue
  candidate=\${dir%/}
  candidate=\${candidate##*/}
  if [ "\$candidate" = "\$version" ]; then
    script="\$dir/scripts/${target}"
    break
  fi
done
if [ ! -f "\$script" ] || [ ! -x "\$script" ]; then
  echo "${name}: cached task-runner \${version} has no executable scripts/${target}" >&2
  exit 127
fi
exec "\$script" "\$@"
EOF_LAUNCHER
  then
    rm -f "$tmp"
    echo "install-launchers: cannot write launcher: $path" >&2
    exit 0
  fi
  chmod 755 "$tmp" 2>/dev/null || { rm -f "$tmp"; echo "install-launchers: cannot set executable mode: $path" >&2; exit 0; }
  if [ -f "$path" ] && [ ! -L "$path" ] && [ -x "$path" ] && cmp -s "$tmp" "$path" 2>/dev/null; then
    rm -f "$tmp"
  else
    mv -fh "$tmp" "$path" 2>/dev/null || { rm -f "$tmp"; echo "install-launchers: cannot replace launcher: $path" >&2; exit 0; }
  fi
done
